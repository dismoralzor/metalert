// Package main — кодогенератор reset: для каждой структуры, помеченной
// комментарием-маркером, генерирует метод Reset(), приводящий её поля к нулевым
// значениям (без аллокации новой структуры — переиспользуются слайсы и мапы).
//
// # Маркер
//
// Генерация включается doc-комментарием над объявлением структуры:
//
//	// generate:reset
//	type Demo struct { ... }
//
// # Что генерируется
//
// В каталоге каждого пакета с помеченными структурами создаётся файл
// reset.gen.go с методами Reset(). Поля сбрасываются по типам:
//   - примитивы — в нулевое значение ("", false, 0);
//   - слайсы — expr = expr[:0] (длина 0, ёмкость сохраняется);
//   - мапы — clear(expr) (мапа пустеет, но остаётся не-nil);
//   - указатели — под защитой if expr != nil (рекурсивно по указуемому типу);
//   - поля, чей тип сам имеет Reset(), — вызовом expr.Reset();
//   - всё прочее — generic-хелпером resetZeroGen (нулевое значение).
//
// Reset() у типа учитывается независимо от того, сгенерирован ли уже
// reset.gen.go, поэтому повторный запуск идемпотентен.
//
// # Запуск
//
// Напрямую (сканирует весь модуль, корень ищется вверх по go.mod):
//
//	go run github.com/dismoralzor/metalert/cmd/reset
//
// Через директиву go:generate (в проекте уже добавлена):
//
//	go generate ./...
//
// Каталог для сканирования можно задать явно:
//
//	go run ./cmd/reset -root .
