// Package main — multichecker статического анализа проекта metalert.
//
// Он объединяет стандартные анализаторы go vet, все SA-проверки staticcheck,
// по одному анализатору из классов simple (S) и stylecheck (ST), два публичных
// анализатора (bodyclose, ineffassign) и собственный анализатор noosexit.
//
// # Запуск
//
// Сборка и запуск по всему проекту:
//
//	go build -o bin/staticlint ./cmd/staticlint
//	./bin/staticlint ./...
//
// Можно запускать и без сборки:
//
//	go run ./cmd/staticlint ./...
//
// Список флагов и справку по конкретному анализатору:
//
//	./bin/staticlint help
//	./bin/staticlint help noosexit
//
// Каждый анализатор включается/отключается флагом по его имени. Отключить
// отдельную проверку:
//
//	./bin/staticlint -SA4006=false ./...
//	./bin/staticlint -noosexit=false ./...
//
// # Анализаторы
//
// Стандартные (go vet) и близкие к ним из golang.org/x/tools:
//
//	asmdecl          — соответствие объявлений ассемблерных функций и их реализаций
//	assign           — бесполезные самоприсваивания (x = x)
//	atomic           — ошибки использования sync/atomic
//	bools            — подозрительные логические выражения (x || !x и т.п.)
//	buildtag         — корректность build-тегов
//	cgocall          — нарушения правил передачи указателей в cgo
//	composite        — безымянные составные литералы из других пакетов
//	copylock         — копирование значений с sync.Locker (мьютексов)
//	directive        — корректность директив //go:
//	errorsas         — второй аргумент errors.As должен быть указателем на error
//	framepointer     — ассемблер, затирающий регистр кадра до его сохранения
//	httpresponse     — ошибки работы с телом HTTP-ответа
//	ifaceassert      — заведомо невозможные проверки типа-интерфейса
//	loopclosure      — захват переменной цикла замыканием
//	lostcancel       — потерянная функция cancel от context.WithCancel и т.п.
//	nilfunc          — бессмысленное сравнение функции с nil
//	nilness          — разыменование заведомо nil и бесполезные проверки на nil
//	printf           — несоответствие форматной строки и аргументов
//	shadow           — затенение переменных во вложенных областях видимости
//	shift            — сдвиги, превышающие разрядность типа
//	sigchanyzer      — небуферизованный канал в signal.Notify
//	slog             — неверные пары ключ-значение в вызовах log/slog
//	stdmethods       — неверные сигнатуры методов стандартных интерфейсов
//	stringintconv    — конверсии int->string (получается руна, а не число)
//	structtag        — корректность тегов полей структур
//	testinggoroutine — вызовы t.Fatal из горутины, отличной от тестовой
//	tests            — ошибки в оформлении тестов, бенчмарков и примеров
//	timeformat       — неверный формат времени (2006-02-01 вместо 2006-01-02)
//	unmarshal        — передача не-указателя в Unmarshal/Decode
//	unreachable      — недостижимый код
//	unsafeptr        — некорректные преобразования uintptr в unsafe.Pointer
//	unusedresult     — проигнорированный результат вызова (например, fmt.Sprintf)
//	unusedwrite      — запись в поле/элемент, которая затем нигде не читается
//
// Анализаторы staticcheck (honnef.co/go/tools):
//
//	SA — все проверки staticcheck на явные ошибки, по диапазонам:
//	     SA1 — неправильное использование стандартной библиотеки;
//	     SA2 — ошибки конкурентности;
//	     SA3 — ошибки в тестах;
//	     SA4 — бесполезный код (код без эффекта);
//	     SA5 — некорректный (сломанный) код;
//	     SA6 — проблемы производительности;
//	     SA9 — подозрительные и, вероятно, ошибочные конструкции.
//	S1000  — упрощения кода (здесь: select с единственным case -> приём из канала)
//	ST1019 — один и тот же пакет импортирован несколько раз
//
// Публичные анализаторы:
//
//	bodyclose   — незакрытое тело HTTP-ответа (resp.Body)
//	ineffassign — присваивание, значение которого нигде не используется
//
// Собственный анализатор:
//
//	noosexit — запрещает прямой вызов os.Exit в функции main пакета main
package main
