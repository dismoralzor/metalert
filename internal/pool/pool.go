// Package pool предоставляет типизированную обёртку над sync.Pool для объектов,
// умеющих сбрасывать своё состояние методом Reset(). Пул переиспользует
// выделенные объекты (и их внутренние буферы - слайсы/мапы), снижая нагрузку на
// сборщик мусора на горячих путях.
package pool

import "sync"

// Resetter - ограничение дженерика: тип умеет сбрасывать своё состояние в
// исходное. Reset вызывается при возврате объекта в пул (см. Pool.Put).
type Resetter interface {
	Reset()
}

// Pool - типизированная обёртка над sync.Pool для объектов с Reset().
//
// Рассчитан на указательные типы (*T): значимый тип при Put в sync.Pool
// упаковывается в interface{} с аллокацией в куче (ровно то, ради избежания чего
// пул и нужен), а Reset у сгенерированных структур объявлен с указательным
// ресивером. Поэтому параметр типа подставляйте как *MyStruct, а фабрика пусть
// возвращает &MyStruct{}.
type Pool[T Resetter] struct {
	p sync.Pool
}

// New создаёт пул. newFn вызывается, когда пул пуст: он обязателен, т.к. для
// указательного T нулевое значение - nil, а пул должен отдавать готовый объект.
func New[T Resetter](newFn func() T) *Pool[T] {
	return &Pool[T]{
		p: sync.Pool{
			New: func() any { return newFn() },
		},
	}
}

// Get возвращает объект из пула либо новый, созданный фабрикой newFn. При
// корректной newFn никогда не возвращает nil.
func (p *Pool[T]) Get() T {
	return p.p.Get().(T)
}

// Put сбрасывает объект через Reset() и возвращает его в пул для повторного
// использования.
func (p *Pool[T]) Put(v T) {
	v.Reset()
	p.p.Put(v)
}
